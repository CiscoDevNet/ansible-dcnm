def prepared_access_nv(ifname=IF7):
    nv = dict((k, v) for k, v in EXP1["branches"]["A"]["member_before"]["intent"]["Ethernet1/8"]["nvPairs"].items() if k != "POLICY_ID")
    nv["INTF_NAME"] = ifname
