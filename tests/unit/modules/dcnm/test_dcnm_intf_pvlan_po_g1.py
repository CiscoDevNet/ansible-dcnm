def po_stanza(mode, lines):
    return (
        ["interface port-channel10", "  switchport", "  switchport mode private-vlan %s" % mode]
        + ["  " + l for l in lines]
        + ["  mtu 9216", "  spanning-tree bpduguard enable", "  spanning-tree port type edge trunk", "  shutdown"]
    )


def member_stanza(mode, lines):
    # G3: the MEASURED expected member form (H1, host), transposed: persisted `channel-group N mode active` (no force) and
    # the parent's PVLAN mode/list lines. For the other modes this is the same form, NOT measured (G5: SYNTHETIC, inferred).
    return [
        "interface ethernet1/7",
        "  channel-group 10 mode active",
        "  mtu 9216",
        "  shutdown",
        "  switchport",
        "  switchport mode private-vlan %s" % mode,
    ] + ["  " + l for l in lines]


