def test_po_with_two_members_and_a_later_unsafe_routed_release_writes_no_member_and_never_deploys():
    """L2: a regular Po with two members; after the mark-delete the first is a safe trunk release (still up) and the SECOND a routed release
    carrying an address. Every member is validated before the first member write: no member modify, no deploy."""
    first, second = "Ethernet1/7", "Ethernet1/9"

    class TwoMembers(PoLifecycleController):
        def __call__(self, mod, method, path, data=None):
            resp = super(TwoMembers, self).__call__(mod, method, path, data)
            if method == "DELETE" and path.endswith(G4.MARKDELETE):
                trunk = V.trunk_host_nv(first)
                trunk["ADMIN_STATE"] = "true"
                self.detail[first] = {"policy": TRUNK, "nvPairs": trunk}
                rnv = dict(RELEASED_ROUTED, INTF_NAME=second, IP="192.0.2.1", PREFIX="24")
                self.detail[second] = {"policy": ROUTED, "nvPairs": rnv}
                self.policies_extra = child_policies(second, CHILDREN_UP)
            return resp

    ctrl = TwoMembers()
    nv = P.po_host_nvpairs(H.po_item(members=[first, second])["profile"], H.PO)
    ctrl.detail[H.PO] = {"policy": H.PO_HOST, "nvPairs": nv}
    ctrl.po_names.add(H.PO)
    for port in (first, second):
        ctrl.detail[port] = {"policy": G4.PO_MEMBER, "nvPairs": {
            "PO_ID": H.PO, "PC_MODE": "active", "PVLAN_MODE": "host", "CDP_ENABLE": "true", "lldpTransmit": "false",
            "lldpReceive": "false", "LACP_PORT_PRIO": "32768", "LACP_RATE": "normal", "DESC": "", "CONF": "", "ADMIN_STATE": "false",
            "INTF_NAME": port}}
    status, result = H.run(ctrl, [{"name": H.PO_ITEM_NAME, "switch": [H.SWITCH_IP], "deploy": True}], state="deleted")
    # the refusal names the port-channel; its cause is the SECOND member's routed address (only the routed release carries IP=)
    assert status == "fail" and "IP='192.0.2.1'" in result["msg"], result.get("msg")
    assert "member release failed while proving the released member before any member write" in result["msg"]
    assert len(ctrl.markdeletes()) == 1 and ctrl.bulk_bodies() == [] and ctrl.deploys() == []
