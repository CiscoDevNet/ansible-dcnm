def remap(lines, port, po_number, pair):
    """The measured Q56 lines on the harness names (port, Po number, association)."""
    out = []
    for line in lines:
        line = line.replace("ethernet1/8", port.lower()).replace("Ethernet1/8", port)
        line = line.replace("port-channel521", "port-channel%s" % po_number).replace("channel-group 521", "channel-group %s" % po_number)
        out.append(line.replace("2410 2412", "%d %d" % pair))
    return out


def routed_release_preview(port=MEM, po_number="502", pair=(2210, 2212), admin_up=False, form="measured"):
    """MEASURED release preview (admin_up=True), the MEASURED preview after the module-equivalent modify (admin_up=False, the default
    form), or the DERIVED admin-down form of the RA1 battery (form="derived": `no shutdown` dropped from the measured release preview)."""
    pv = Q56["preview_release_admin_up"] if admin_up or form == "derived" else Q56["preview_release_admin_down_measured"]
    pending = remap(pv["pendingConfig"], port, po_number, pair)
    expected = remap(pv["expected_member"], port, po_number, pair)
    if not admin_up and form == "derived":
        pending = [line for line in pending if line.strip() != "no shutdown"]
        expected = [("  shutdown" if line.strip() == "no shutdown" else line) for line in expected]
    return pending, remap(pv["running_member"], port, po_number, pair), expected


def child_policies(port, templates, serial="x"):
    return [{"entityName": port, "entityType": "INTERFACE", "templateName": t, "source": port, "deleted": False,
             "policyId": "POLICY-77%03d" % i, "priority": prio, "serialNumber": serial} for i, (t, prio) in enumerate(templates)]


class RoutedReleaseController(G4.ReleaseController):
    """The G4 release harness + the MEASURED routed release and its own children. `swap_children` (MEASURED: the modify that sets the
    released routed member down regenerated its children with shut_interface 458 in place of no_shut_interface): a SUCCESS modify that sets the
    member down turns its own no_shut_interface into shut_interface. `children_after_deploy`: extra live policies that appear after the
    deploy (final-verification negatives)."""

    def __init__(self):
        super(RoutedReleaseController, self).__init__()
        self.released_policy = ROUTED
        self.released_nv = copy.deepcopy(RELEASED_ROUTED)
        self.extra_after_delete = child_policies(MEM, CHILDREN_UP)
        self.swap_children = True
        self.children_after_deploy = []

    def __call__(self, mod, method, path, data=None):
        resp = super(RoutedReleaseController, self).__call__(mod, method, path, data)
        if method == "POST" and path.endswith(G4.MODIFY) and self.swap_children and self.detail.get(MEM, {}).get("policy") == ROUTED:
            if str(self.detail[MEM]["nvPairs"].get("ADMIN_STATE")).lower() == "false":
                for p in self.policies_extra:
                    if p["entityName"] == MEM and p["templateName"] == "no_shut_interface":
                        p["templateName"], p["priority"] = "shut_interface", 458
        if method == "POST" and path.endswith(G4.DEPLOY) and self.children_after_deploy:
            self.policies_extra = self.policies_extra + list(self.children_after_deploy)
        return resp


def routed_ctrl(**knobs):
    ctrl = G4.owned_ctrl()
    ctrl.__class__ = RoutedReleaseController
    ctrl.released_policy = ROUTED
    ctrl.released_nv = copy.deepcopy(RELEASED_ROUTED)
    ctrl.extra_after_delete = child_policies(MEM, CHILDREN_UP)
    ctrl.swap_children = True
    ctrl.children_after_deploy = []
    pending, running, expected = routed_release_preview()
    ctrl.previews = [{"RETURN_CODE": 200, "MESSAGE": "OK", "DATA": [preview(pending, running=running, expected=expected)["DATA"][0]]}]
    for k, v in knobs.items():
        setattr(ctrl, k, v)
    return ctrl


def delete(ctrl):
    return G4.delete(ctrl)


