"""Mode 'peer_link': updates of an existing vPC peer-link port-channel (int_vpc_peer_link_po).

The vPC pairing creates the peer-link on each peer and owns everything except four keys. These tests drive the real
main() and assert what the module sends: one interface/modify per peer serial, the requested keys, every other stored
nvPair byte-equal, and no request at all for a refused item. The HAVE and detail rows have the shape of a saved
controller read; every value is synthetic. They make no claim about the template or the device.
"""
from __future__ import absolute_import, division, print_function

__metaclass__ = type

import copy
import json
from urllib.parse import parse_qs, urlsplit

from unittest.mock import patch

import pytest

from ansible_collections.cisco.dcnm.plugins.module_utils.gie_binding_table import resolve_binding
