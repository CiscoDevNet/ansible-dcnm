# ------------------------------------------------------------------ merged
def test_merged_stp_sends_one_modify_per_peer_and_preserves_every_other_nvpair():
    result, calls = _run(_cfg(spanning_tree_port_type="network"), "merged", _have())
    assert not result.get("failed"), result.get("msg")
    sent = _modifies(calls)
    assert set(sent) == set(SERIALS)
    for serial in SERIALS:
        nv = sent[serial]
        assert nv["spanningTreePortType"] == "network"
        for k in PRESERVED:
            assert nv[k] == STORED[k], k
        assert "POLICY_ID" not in nv and "SPEED" not in nv


def _paths(calls):
    return [c["method"] + " " + c["path"].split("/rest/")[-1].split("?")[0] for c in h.writes(calls)]


def test_merged_stp_uses_the_ordinary_port_channel_requests():
    result, calls = _run(_cfg(spanning_tree_port_type="normal"), "merged", _have())
    assert not result.get("failed"), result.get("msg")
    assert _paths(calls) == ["POST interface/modify", "POST globalInterface/deploy"]
    deployed = [d for c in h.writes(calls) if c["path"].endswith("deploy") for d in c["payload"]]
    assert sorted(d["serialNumber"] for d in deployed) == sorted(SERIALS)
    assert all(d["ifName"].lower() == PO for d in deployed)


