from ansible_collections.cisco.dcnm.tests.unit.modules.dcnm import gie_withdrawal_harness as h

PL = "int_vpc_peer_link_po"
PO = "port-channel1"
SERIALS = (h.SERIAL, h.PEER_SERIAL)

# The stored nvPairs of a peer-link intent, in the shape of a saved read (values synthetic).
STORED = {
    "MEMBER_INTERFACES": "Ethernet1/3,Ethernet1/4",
    "PO_ID": PO,
    "MEMBER_DESC": "",
    "ADMIN_STATE": "true",
    "PRIORITY": "202",
    "POLICY_DESC": "",
    "CONF": "",
    "NATIVE_VLAN": "",
    "POLICY_ID": "POLICY-1001",
    "PTP": "false",
    "DESC": "",
}
# Sent back unchanged in every write; POLICY_ID and POLICY_DESC are controller metadata the module never sends.
PRESERVED = sorted(k for k in STORED if k not in ("POLICY_ID", "POLICY_DESC"))


def _intent(serial, policy=PL, **stored):
    return {"policy": policy, "interfaces": [{
        "serialNumber": serial, "ifName": PO, "interfaceType": "INTERFACE_PORT_CHANNEL", "fabricName": h.FABRIC,
        "nvPairs": dict(STORED, **stored)}]}


def _have(policy=PL, **stored):
    return [_intent(s, policy, **stored) for s in SERIALS]


def _detail_row(serial, policy=PL, source="", if_type="INTERFACE_PORT_CHANNEL"):
    return {
        "ifName": "Port-channel1", "serialNo": serial, "fabricName": h.FABRIC, "ifType": if_type,
        "isPhysical": "false", "markDeleted": False, "deletable": True, "editAllowed": True,
        "alias": '"vpc-peer-link sw-1--sw-2"', "deleteReason": None, "complianceStatus": "In-Sync",
        "underlayPolicies": [{"templateName": policy, "entityName": PO, "source": source, "serialNumber": serial,
                              "autoGenerated": True}],
    }


def _transport(detail=None, pairs=None):
    """Controller double in the shape of the saved reads: the intent read returns only the queried peer, and the
    detail read of either peer returns the rows of both."""
    def factory(calls, have):
        def send(mod, method, path, payload=None):
            parsed = json.loads(payload) if isinstance(payload, str) else copy.deepcopy(payload)
            calls.append({"method": method, "path": path, "payload": parsed})
            if method != "GET":
                return {"RETURN_CODE": 200, "MESSAGE": "OK", "DATA": []}
            query = parse_qs(urlsplit(path).query)
            serial = (query.get("serialNumber") or [None])[0]
            if "vpcpair_serial_number" in path:
                asked = (query.get("serial_number") or [None])[0]
                return {"RETURN_CODE": 200, "MESSAGE": "OK",
                        "DATA": {"vpc_pair_sn": (pairs or {}).get(asked, h.VPC_PAIR_SERIAL)}}
            if "readonly" in path or "accessmode" in path.lower():
                return {"RETURN_CODE": 200, "MESSAGE": "OK", "DATA": {"readonly": False}}
            if "/interface/detail" in path:
                rows = detail if detail is not None else [_detail_row(s) for s in SERIALS]
                return {"RETURN_CODE": 200, "MESSAGE": "OK", "DATA": copy.deepcopy(rows)}
            if "/interface?" in path:
                return {"RETURN_CODE": 200, "MESSAGE": "OK", "DATA": [
                    copy.deepcopy(p) for p in have
                    if serial is None or p["interfaces"][0]["serialNumber"] == serial]}
            return {"RETURN_CODE": 200, "MESSAGE": "OK", "DATA": []}
        return send
    return factory


def _cfg(switch=None, deploy=True, **profile):
    return {"name": "po1", "type": "pc", "switch": list(switch or (h.SWITCH_IP, h.PEER_IP)), "deploy": deploy,
            "profile": dict({"mode": "peer_link"}, **profile)}


def _run(configs, state, have, detail=None, pairs=None, **kw):
    return h.run_configs(configs if isinstance(configs, list) else [configs], state, have,
                         transport=_transport(detail, pairs), pair=True, **kw)


def _modifies(calls):
    """{serial: nvPairs} of every interface/modify, asserting one policy entry per peer."""
    out = {}
    for c in h.writes(calls):
        if "interface/modify" not in c["path"]:
            continue
        for pol in c["payload"] if isinstance(c["payload"], list) else [c["payload"]]:
            assert pol["policy"] == PL, pol["policy"]
            for intf in pol["interfaces"]:
                assert intf["ifName"].lower() == PO
                assert intf["serialNumber"] not in out, "two modifies for one peer"
                out[intf["serialNumber"]] = intf["nvPairs"]
    return out


def _assert_refused(result, calls, *words):
    assert result.get("failed"), "the item was not refused"
    assert h.writes(calls) == [], [c["method"] + " " + c["path"] for c in h.writes(calls)]
    for w in words:
        assert w in result["msg"], result["msg"]
    assert "no change was sent" in result["msg"].lower() or "No configuration" in result["msg"], result["msg"]


