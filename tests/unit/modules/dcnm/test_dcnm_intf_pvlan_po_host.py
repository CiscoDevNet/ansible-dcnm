# ------------------------------------------------------------------ route, payload types, creation
def test_creation_real_route_payload_types_and_order():
    ctrl = baseline_ctrl()
    ctrl.previews = [good_preview()]
    status, result = run(ctrl, [po_item()])
    assert status == "exit" and result["changed"] is True, result
    assert len(ctrl.creates()) == 1 and ctrl.requests("POST", MODIFY) == []
    body = json.loads(ctrl.creates()[0][2])
    payload = body[0] if isinstance(body, list) else body
    assert payload["policy"] == PO_HOST
    nv = payload["interfaces"][0]["nvPairs"]
    # D2: declared types. LACP_PORT_PRIO is an integer; LACP_RATE and PORT_DUPLEX_MODE are strings.
    assert nv["LACP_PORT_PRIO"] == 32768 and isinstance(nv["LACP_PORT_PRIO"], int)
    assert nv["LACP_RATE"] == "normal" and nv["PORT_DUPLEX_MODE"] == "auto"
    assert nv["PC_MODE"] == "active" and nv["MTU"] == "jumbo" and nv["SPEED"] == "Auto" and nv["BPDUGUARD_ENABLED"] == "true"
    assert nv["ADMIN_STATE"] == "false" and nv["MEMBER_INTERFACES"] == IF7 and nv["PO_ID"] == PO
    # HOST:424 evaluates PVLAN_NATIVE_VLAN even in host mode: the neutral wire form is the empty STRING
    # measured in the Ethernet writes; never the integer 1 (1 != "1") and never an omitted key.
    assert nv["PVLAN_NATIVE_VLAN"] == "" and isinstance(nv["PVLAN_NATIVE_VLAN"], str)
    assert nv["PVLAN_ALLOWED_VLANS"] == "" and nv["CONF"] == ""
    assert P.pairs_from_wire(nv["ASSOCIATION_LIST"], "ASSOCIATION_LIST") == [(PRIMARY, SECONDARY)]
    # preview generated BEFORE the deploy; nothing outside the legacy path
    order = ctrl.order()
    assert order.index("PREVIEW") < order.index("DEPLOY") and ctrl.manage() == []
    # the parent writes the member: no direct write to the member interface
    entries = [i["ifName"] for c in ctrl.creates() for p in _as_list(json.loads(c[2])) for i in p["interfaces"]]
    assert entries == [PO], "only the parent is created; the member appears solely inside MEMBER_INTERFACES"
    assert result.get("pvlan_gate")[0]["targets"][PO] == "deploy"


