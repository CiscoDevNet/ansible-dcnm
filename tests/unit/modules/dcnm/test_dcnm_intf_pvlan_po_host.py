def test_replaced_states_the_complete_model_and_updates_only_the_differing_keys():
    # G1 (scope change): `replaced` on an existing PVLAN port-channel is an UPDATE to the complete model (E6
    # contract): an omitted description is the template declaration "". E2 refused every update.
    ctrl = created_ctrl()
    ctrl.detail[PO]["nvPairs"]["DESC"] = "kept from have"
    status, result = run(ctrl, [po_item(deploy=False)], state="replaced")
    assert status == "exit" and result["changed"] is True, result
    bodies = [json.loads(c[2]) for c in ctrl.calls if c[0] == "POST" and "bulk-update" in c[1] or c[1].endswith(MODIFY)]
    sent = [i["nvPairs"] for b in bodies for p in (b if isinstance(b, list) else [b]) for i in p["interfaces"]]
    assert len(sent) == 1 and sent[0]["DESC"] == "" and sent[0]["ASSOCIATION_LIST"] == ctrl.detail[PO]["nvPairs"]["ASSOCIATION_LIST"]
    assert result["diff"][0]["replaced"][0]["interfaces"][0]["nvPairs"] == {"DESC": ""}, "the diff is exactly the change"
    assert ctrl.creates() == [] and ctrl.deploys() == []


