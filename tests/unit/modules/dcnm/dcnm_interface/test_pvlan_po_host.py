def edit_member_pending(pf, old=None, new=None, add=None):
    pf = copy.deepcopy(pf)
    pend = pf["pendingConfig"]
    if old is not None:
        i = pend.index(old)
        if new is None:
            pend.pop(i)
        else:
            pend[i] = new
    if add:
        i = len(pend) - 1  # before the member block's closing `configure terminal`
        pend[i:i] = add
    return pf


