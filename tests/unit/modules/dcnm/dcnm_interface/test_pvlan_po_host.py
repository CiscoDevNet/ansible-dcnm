class T2Controller(PoLifecycleController):
    """The existing Po harness (PoController + lifecycle) seeded with the MEASURED intents. Its mark-delete removes the parent
    and leaves the member as the controller released it (`released_nv`, default: the measured R1 release)."""

    def __init__(self, stage_name):
        super(T2Controller, self).__init__()
        po, mem = intent(stage_name, PO_REFUSALS_PO), intent(stage_name, PO_REFUSALS_MEM)
        self.detail[PO_REFUSALS_PO] = {"policy": po["policy"], "nvPairs": po_refusals_harness_nv(po["nvPairs"])}
        self.po_names.add(PO_REFUSALS_PO)
        self.detail[PO_REFUSALS_MEM] = {"policy": mem["policy"], "nvPairs": po_refusals_harness_nv(mem["nvPairs"])}
        self.released_nv = copy.deepcopy(RELEASED)

    def __call__(self, mod, method, path, data=None):
        if method == "DELETE" and path.endswith(MARKDELETE):
            self.calls.append((method, path, data))
            self.detail.pop(PO_REFUSALS_PO, None)
            self.po_names.discard(PO_REFUSALS_PO)
            self.detail[PO_REFUSALS_MEM] = {"policy": TRUNK, "nvPairs": copy.deepcopy(self.released_nv)}
            return markdelete_ok(data)
        return super(T2Controller, self).__call__(mod, method, path, data)

    def kinds(self):
        out = []
        for m, p, _d in self.calls:
            if m == "DELETE" and p.endswith(MARKDELETE):
                out.append("markdelete")
            elif m == "POST" and p.endswith(PO_REFUSALS_MODIFY):
                out.append("modify")
            elif m == "POST" and p.endswith(DEPLOY):
                out.append("deploy")
        return out

    def modify_nv(self, ifname):
        bodies = [json.loads(c[2]) for c in self.calls if c[0] == "POST" and c[1].endswith(PO_REFUSALS_MODIFY)]
        found = [i["nvPairs"] for b in bodies for p in b for i in p["interfaces"] if i["ifName"].lower() == ifname.lower()]
        return found


