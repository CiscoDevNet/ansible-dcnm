@pytest.mark.parametrize(
    "mode, profile, lines, check",
    [
        (
            "promiscuous",
            {"pvlan_mapping": MAP_2212},
            ["switchport private-vlan mapping 2210 2212"],
            lambda nv: P.pairs_from_wire(nv["MAPPING_LIST"], "MAPPING_LIST") == [(2210, 2212)] and nv["ASSOCIATION_LIST"] == "",
        ),
        (
            "trunk promiscuous",
            {"pvlan_mapping": [{"primary_vlan": 2210, "secondary_vlans": "2211-2212"}], "native_vlan": "2301", "allowed_vlans": "2301"},
            [
                "switchport private-vlan trunk native vlan 2301",
                "switchport private-vlan trunk allowed vlan 2301",
                "switchport private-vlan mapping trunk 2210 2211",
                "switchport private-vlan mapping trunk 2210 2212",
            ],
            lambda nv: nv["PVLAN_NATIVE_VLAN"] == "2301"
            and nv["PVLAN_ALLOWED_VLANS"] == "2301"
            and P.pairs_from_wire(nv["MAPPING_LIST"], "MAPPING_LIST") == [(2210, 2211), (2210, 2212)],
        ),
        (
            "trunk secondary",
            {"pvlan_association": [{"primary_vlan": 2210, "secondary_vlan": 2212}], "native_vlan": "2301", "allowed_vlans": "2301"},
            [
                "switchport private-vlan trunk native vlan 2301",
                "switchport private-vlan trunk allowed vlan 2301",
                "switchport private-vlan association trunk 2210 2212",
            ],
            lambda nv: P.pairs_from_wire(nv["ASSOCIATION_LIST"], "ASSOCIATION_LIST") == [(2210, 2212)] and nv["MAPPING_LIST"] == "",
        ),
        (
            "host",
            {"pvlan_association": [{"primary_vlan": 2210, "secondary_vlan": 2212}]},
            ["switchport private-vlan host-association 2210 2212"],
            lambda nv: nv["PVLAN_NATIVE_VLAN"] == "" and nv["PVLAN_ALLOWED_VLANS"] == "",
        ),
    ],
)
def test_creation_in_each_mode_payload_types_gate_and_member_model(mode, profile, lines, check):
    # The four modes run through main(); host on the measured force form, the others on the inferred one.
    # Trunk secondary from the prepared access member.
    ctrl = baseline(mode)
    ctrl.previews = [create_preview(mode, lines)]
    status, result = run(ctrl, [item(mode, **profile)], state="replaced")
    assert status == "exit" and result["changed"] is True, result.get("msg")
    assert len(ctrl.creates()) == 1 and len(ctrl.deploys()) == 1 and ctrl.bulk_bodies() == []
    body = json.loads(ctrl.creates()[0][2])
    body = body[0] if isinstance(body, list) else body
    nv = body["interfaces"][0]["nvPairs"]
    assert body["policy"] == PO_HOST and nv["PVLAN_MODE"] == mode and nv["ADMIN_STATE"] == "false" and check(nv)
    assert nv["MEMBER_INTERFACES"] == IF7 and isinstance(nv["LACP_PORT_PRIO"], int)
    assert not any(k.startswith("__") for k in nv), "the member model's internal keys never reach a payload"
    assert result["pvlan_gate"][0]["targets"][PO] == "deploy"


