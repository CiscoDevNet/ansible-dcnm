def p2_preview():
    run_po = po_stanza("promiscuous", ["switchport private-vlan mapping 2210 2212"])
    run_m = member_stanza("promiscuous", ["switchport private-vlan mapping 2210 2212"])
    pend = ["interface port-channel10", "  switchport private-vlan mapping 2210 2211", "interface Ethernet1/7", "  switchport private-vlan mapping 2210 2211"]
