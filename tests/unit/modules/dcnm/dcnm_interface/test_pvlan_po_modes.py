    assert status == "exit" and result["changed"] is True, result.get("msg")
    assert ctrl.creates() == [] and len(ctrl.bulk_bodies()) == 1 and len(ctrl.deploys()) == 1
    sent = ctrl.bulk_bodies()[0][0]["interfaces"][0]["nvPairs"]
    assert P.pairs_from_wire(sent["MAPPING_LIST"], "MAPPING_LIST") == [(2210, 2211), (2210, 2212)]
    for key in ("ADMIN_STATE", "DESC", "MEMBER_INTERFACES", "PC_MODE", "MTU", "BPDUGUARD_ENABLED", "LACP_PORT_PRIO"):
        assert sent[key] == have[key], key
    assert result["diff"][0]["merged"][0]["interfaces"][0]["nvPairs"] == {"MAPPING_LIST": sent["MAPPING_LIST"]}
    assert result["pvlan_gate"][0]["targets"][PO] == "deploy"


