def test_vpc_routed_second_write_failure_keeps_the_partial_diagnosis_and_no_deploy():
    class FailSecond(RoutedVpc):
        def __call__(self, mod, method, path, data=None):
            if method == "POST" and path.endswith(V.MODIFY) and any(i["ifName"] == V.M2 for p in json.loads(data) for i in p["interfaces"]):
                self.calls.append((method, path, data))
                return {"RETURN_CODE": 207, "MESSAGE": "Multi-Status",
                        "DATA": [{"reportItemType": "ERROR", "message": "injected", "entity": "%s~%s" % (V.SN2, V.M2)}]}
            return super(FailSecond, self).__call__(mod, method, path, data)
    ctrl = seeded_vpc({(V.SN2, V.M2)})
    ctrl.__class__ = FailSecond
    status, result = V.run_vpc(ctrl, [V.vpc_del_item()], state="deleted")
    assert status == "fail" and ctrl.deploys() == [], result.get("msg")
    assert "at the member modify" in result["msg"] and "=uncertain" in result["msg"], result["msg"]
    assert "=confirmed" in result["msg"], "the earlier member writes stay reported as confirmed"


