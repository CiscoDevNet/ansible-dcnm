# ------------------------------------------------------------------ vPC: per peer, mixed policies, peer order, multiple members
VPC_PORTS = {V.SN1: [V.M1, "Ethernet1/9"], V.SN2: [V.M2]}


class RoutedVpc(V.VpcController):
    """The vPC harness releasing chosen ports as the MEASURED routed form (DERIVED for a vPC child), with their own up children; a SUCCESS
    modify that sets a routed port down turns its no_shut_interface into shut_interface (DERIVED)."""

    routed_ports = frozenset()
    released_down = False
    routed_nv = RELEASED_ROUTED

    def __call__(self, mod, method, path, data=None):
        resp = super(RoutedVpc, self).__call__(mod, method, path, data)
        if method == "DELETE" and path.endswith(V.MARKDELETE):
            for serial, port in self.routed_ports:
                nv = copy.deepcopy(self.routed_nv)
                nv["INTF_NAME"] = port
                if self.released_down:
                    nv["ADMIN_STATE"] = "false"
                self.nodes[serial][port] = {"policy": ROUTED, "nvPairs": nv}
                kids = CHILDREN_UP if not self.released_down else [("routed_interface", 450), ("interface_mtu", 452), ("shut_interface", 458)]
                self.policies_extra[serial] += child_policies(port, kids, serial)
        if method == "POST" and path.endswith(V.MODIFY):
            for payload in json.loads(data):
                for intf in payload["interfaces"]:
                    if payload["policy"] == ROUTED and intf["nvPairs"].get("ADMIN_STATE") == "false":
                        for p in self.policies_extra[intf["serialNumber"]]:
                            if p["entityName"] == intf["ifName"] and p["templateName"] == "no_shut_interface":
                                p["templateName"], p["priority"] = "shut_interface", 458
        return resp


def routed_vpc_delete_preview(serial, port, pair=(V.PRIMARY, V.SECONDARY)):
    pending, _running, expected = routed_release_preview(port=port, po_number="10", pair=pair)
    return V.preview(["no interface port-channel10"] + pending[1:], serial=serial, running=V.po_stanza(pair) + V.member_after(port, pair),
                     expected=expected)


def seeded_vpc(routed, released_down=False, ports=None, released=None):
    ports = ports or VPC_PORTS
    ctrl = V.VpcController()
    for serial, plist in ports.items():
        for port in plist:
            nv = V.trunk_host_nv(port)
            nv["ADMIN_STATE"] = "false"
            ctrl.nodes[serial][port] = {"policy": V.TRUNK, "nvPairs": nv}
    ctrl = ctrl.seed_vpc()
    nv = ctrl.parents[V.VPC]["nvPairs"]
    for n, serial in enumerate((V.SN1, V.SN2), 1):
        nv["PEER%d_MEMBER_INTERFACES" % n] = ",".join(ports[serial])
    ctrl._expand_children(nv)
    ctrl.next_invocation()
    ctrl.__class__ = RoutedVpc
    ctrl.routed_ports = frozenset(routed)
    ctrl.released_down = released_down
    ctrl.routed_nv = RELEASED_ROUTED if released is None else released
    for serial, plist in ports.items():
        ctrl.vpc_previews[serial].append(_combine(serial, plist, routed))
    return ctrl


def _combine(serial, plist, routed):
    fields = {"pendingConfig": [], "runningConfig": [], "expectedConfig": []}
    for i, port in enumerate(plist):
        factory = routed_vpc_delete_preview if (serial, port) in routed else V.delete_preview
        entry = P.preview_entry(factory(serial, port), serial)
        for key in fields:
            current = None
            for line in entry[key]:
                if line.lower().strip().startswith("interface "):
                    current = line.lower().strip()[10:]
                if i and (current == "port-channel10" or line.lower().strip() == "no interface port-channel10"):
                    continue
                fields[key].append(line)
    return V.preview(fields["pendingConfig"], serial=serial, running=fields["runningConfig"], expected=fields["expectedConfig"])


def test_vpc_mixed_trunk_and_routed_releases_are_corrected_per_member_and_verified():
    routed = {(V.SN1, "Ethernet1/9"), (V.SN2, V.M2)}
    ctrl = seeded_vpc(routed)
    status, result = V.run_vpc(ctrl, [V.vpc_del_item()], state="deleted")
    assert status == "exit", result.get("msg")
    assert len(ctrl.markdeletes()) == 1 and len(ctrl.modifies()) == 3 and len(ctrl.deploys()) == 1
    sent = dict(((i["serialNumber"], i["ifName"]), p["policy"]) for c in ctrl.modifies() for p in json.loads(c[2]) for i in p["interfaces"])
    assert sent == {(V.SN1, V.M1): TRUNK, (V.SN1, "Ethernet1/9"): ROUTED, (V.SN2, V.M2): ROUTED}, "each member keeps ITS released policy"
    records = dict(((r["serial"], r["member"]), r["released_policy"]) for r in result["pvlan_vpc_release"] if "released_policy" in r)
    assert records == sent
    order = ctrl.order()
    assert max(i for i, x in enumerate(order) if x == "MODIFY") < order.index("DEPLOY")
    assert result["pvlan_verification"][V.VPC]["state"] == "verified"


