# Formerly test_dcnm_intf_pvlan_release_routed.py
# Release of a PVLAN port-channel / vPC member as int_routed_host besides int_trunk_host.
#
# MEASURED inputs (fixtures/pvlan_routed_release.json#pvlan_release_routed_q56_measured, live runs on a switch whose fabric role is not leaf): the member
# released by the controller after the mark-delete of a deployed PVLAN Po (int_routed_host, 83 writable nvPairs + POLICY_ID,
# ADMIN_STATE "true"), its own child policies (routed_interface 450, interface_mtu 452, no_shut_interface 452, source = the member),
# the fresh preview at that point (pending `no channel-group ... force` / PVLAN withdrawals / `no switchport` / `mtu 9216` /
# `no shutdown`; expected `mtu 9216 / no shutdown / no switchport`), the admin-down routed baseline of the same port (expected
# `mtu 9216 / no switchport / shutdown`) and -- after a modify equivalent to the module's (same policy, every writable nvPair, only
# ADMIN_STATE false) -- the preview (the same pending with `shutdown` in place of `no shutdown`; expected `mtu 9216 / no switchport /
# shutdown`) and the own children regenerated by that modify (routed_interface 450, interface_mtu 452, shut_interface 458).
#
# DERIVED, NOT MEASURED: an earlier admin-down form (`no shutdown` simply dropped), kept as a compatibility case; the vPC child
# releasing the same way (only a regular Po was measured). Names are mapped onto the existing harnesses. Real main(); only the
# controller boundary is intercepted (existing Po and vPC harnesses, subclassed here).
# ====================================================================================================
class RoutedReleaseController(G4.ReleaseController):
    """The Po release harness + the MEASURED routed release and its own children. `swap_children` (MEASURED: the modify that sets the
    released routed member down regenerated its children with shut_interface 458 in place of no_shut_interface): a SUCCESS modify that sets the
    member down turns its own no_shut_interface into shut_interface. `children_after_deploy`: extra live policies that appear after the
    deploy (final-verification negatives)."""

    def __init__(self):
        super(RoutedReleaseController, self).__init__()
        self.released_policy = ROUTED
        self.released_nv = copy.deepcopy(RELEASED_ROUTED)
        self.extra_after_delete = child_policies(MEM, CHILDREN_UP)
        self.swap_children = True
        self.children_after_deploy = []

    def __call__(self, mod, method, path, data=None):
        resp = super(RoutedReleaseController, self).__call__(mod, method, path, data)
        if method == "POST" and path.endswith(G4.MODIFY) and self.swap_children and self.detail.get(MEM, {}).get("policy") == ROUTED:
            if str(self.detail[MEM]["nvPairs"].get("ADMIN_STATE")).lower() == "false":
                for p in self.policies_extra:
                    if p["entityName"] == MEM and p["templateName"] == "no_shut_interface":
                        p["templateName"], p["priority"] = "shut_interface", 458
        if method == "POST" and path.endswith(G4.DEPLOY) and self.children_after_deploy:
            self.policies_extra = self.policies_extra + list(self.children_after_deploy)
        return resp


def routed_ctrl(**knobs):
    ctrl = G4.owned_ctrl()
    ctrl.__class__ = RoutedReleaseController
    ctrl.released_policy = ROUTED
    ctrl.released_nv = copy.deepcopy(RELEASED_ROUTED)
    ctrl.extra_after_delete = child_policies(MEM, CHILDREN_UP)
    ctrl.swap_children = True
    ctrl.children_after_deploy = []
    pending, running, expected = routed_release_preview()
    ctrl.previews = [{"RETURN_CODE": 200, "MESSAGE": "OK", "DATA": [preview(pending, running=running, expected=expected)["DATA"][0]]}]
    for k, v in knobs.items():
        setattr(ctrl, k, v)
    return ctrl


def delete(ctrl):
    return G4.delete(ctrl)


